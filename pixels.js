const GLYPH_W = 5;
const GLYPH_H = 7;
const SPACE_W = 3;

const charWidth = (ch) => (ch === ' ' ? SPACE_W : GLYPH_W);

// Lays out lines of text as centred voxel coordinates (y up).
export function textToVoxels(lines, { letterGap = 1, lineGap = 3 } = {}) {
  const upper = lines.map((l) => [...l.toUpperCase()]);
  const lineWidths = upper.map((chars) => chars.reduce((w, ch, i) => w + charWidth(ch) + (i ? letterGap : 0), 0));
  const width = Math.max(...lineWidths);
  const height = lines.length * GLYPH_H + (lines.length - 1) * lineGap;
  const voxels = [];

  upper.forEach((chars, li) => {
    let x = -lineWidths[li] / 2;
    const y0 = height / 2 - li * (GLYPH_H + lineGap);
    chars.forEach((ch) => {
      const glyph = GLYPHS[ch];
      glyph?.forEach((row, ry) => {
        [...row].forEach((cell, rx) => {
          if (cell === '#') voxels.push({ x: x + rx + 0.5, y: y0 - ry - 0.5, row: ry });
        });
      });
      x += charWidth(ch) + letterGap;
    });
  });

  return { voxels, width, height };
}

// Greedy word wrap for voxel text; long single words stay whole.
export function wrapText(text, maxChars) {
  const lines = [];
  for (const word of text.trim().split(/\s+/)) {
    const last = lines[lines.length - 1];
    if (last && last.length + 1 + word.length <= maxChars) lines[lines.length - 1] = `${last} ${word}`;
    else lines.push(word);
  }
  return lines;
}

