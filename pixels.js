// Builds a crisp SVG from pixel rows, merging horizontal runs into single rects.
export function pixelIcon(id) {
  const rows = ICONS[id];
  if (!rows) return '';
  const w = Math.max(...rows.map((r) => r.length));
  let rects = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (row[x] === '#') x++;
      rects += `<rect x="${start}" y="${y}" width="${x - start}" height="1"/>`;
    }
  });
  return `<svg viewBox="-1 -1 ${w + 2} ${w + 2}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><g fill="currentColor" transform="translate(0 ${(w - rows.length) / 2})">${rects}</g></svg>`;
}
